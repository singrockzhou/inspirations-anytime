/** 按 id 取一条。detail 页只认这个函数，不认数组下标。 */
function byId(id) {
  const key = String(id || '')
  for (let i = 0; i < LIST.length; i++) {
    if (LIST[i].id === key) return LIST[i]
  }
  return null
}

/** 取某个分类下的模板，保持 LIST 里的顺序 */
function byCat(cat) {
  return LIST.filter(function (item) {
    return item.cat === cat
  })
}

/** 分类 + 该类条目，页面直接拿这个渲染，不用二次遍历 */
function groups() {
  return CATS.map(function (c) {
    return {
      id: c.id,
      name: c.name,
      desc: c.desc,
      items: byCat(c.id)
    }
  }).filter(function (g) {
    return g.items.length > 0
  })
}

